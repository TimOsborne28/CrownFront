function effect(kind, frame, count) {
  const t = frame / (count - 1);
  if (kind === "sword")
    return `<g transform="translate(${12 * (1 - t)} ${-8 * (1 - t)}) rotate(${-25 + t * 35} 32 32)" opacity="${1 - t * 0.7}">${mono(sword, "#f7dea1")}</g>`;
  if (kind === "sail")
    return `<g transform="translate(0 ${t * 33}) rotate(${t * 35} 32 48)" opacity="${1 - t * 0.9}">${galley(
      true,
    )
      .replace(/#ebebeb/g, "#dfcca0")
      .replace(/#b4b4b4/g, "#8f5532")}</g>`;
  if (kind === "smoke" || kind === "dust")
    return [0, 1, 2, 3, 4]
      .map((i) =>
        circle(
          12 + i * 10 + Math.sin(i + t * 5) * 4,
          44 - t * 24 - (i % 2) * 8,
          8 + t * 7,
          kind === "dust" ? "#c9b583" : "#6a5d47",
        ),
      )
      .join("");
  if (kind === "flame")
    return (
      path(
        `M12 60Q2 42 22 ${17 + Math.sin(t * 6.28) * 9}Q16 39 30 36Q27 12 39 3Q37 26 51 35Q65 56 49 62Z`,
        "#a43c20",
      ) +
      path("M22 61Q13 50 33 28Q28 45 42 37Q56 58 41 63Z", "#efa331") +
      path("M29 60Q24 51 35 44L40 61Z", "#ffe5a0")
    );
  let body = "";
  if (kind === "fire")
    body +=
      circle(32, 32, 6 + Math.sin(t * Math.PI) * 21, "#b94621") +
      circle(32, 32, 3 + Math.sin(t * Math.PI) * 15, "#efb345");
  for (let i = 0; i < 9; i++) {
    const a = (i * Math.PI * 2) / 9 + frame * 0.09;
    const r = 5 + t * 23;
    const x = 32 + Math.cos(a) * r;
    const y = 32 + Math.sin(a) * r;
    const size = Math.max(1, (1 - t) * (kind === "rubble" ? 8 : 6));
    body += path(
      `M${x - size} ${y}l${size} ${-size * 1.5}l${size} ${size}l${-size * 0.6} ${size * 1.4}Z`,
      kind === "rubble"
        ? ["#69563a", "#baa377", "#e2c99a"][i % 3]
        : ["#ffdb78", "#c75d24", "#f3a62c"][i % 3],
    );
  }
  return `<g opacity="${1 - t * 0.75}">${body}</g>`;
}
